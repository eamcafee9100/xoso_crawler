import re

# Dữ liệu đầu vào
text = "24 (4395.714285714285) 04 (4365.714285714286) 78 (4335.714285714285) 57 (3998.571428571429) 58 (3967.142857142857) 45 (3934.285714285714) 76 (3905.714285714286) 06 (3537.142857142857) 09 (3507.142857142857) 10 (3507.142857142857) 74 (3507.142857142857) 22 (3505.714285714286) 36 (3478.5714285714294) 77 (3477.1428571428573) 91 (3475.714285714286) 63 (3140.0) 30 (3137.1428571428573) 99 (3107.1428571428573) 07 (3104.2857142857147) 18 (31)"

# Loại bỏ số trong dấu ngoặc và thay bằng ", "
result = re.sub(r'\s*\([^)]+\)', ', ', text)

# Xóa khoảng trắng thừa ở đầu và cuối
